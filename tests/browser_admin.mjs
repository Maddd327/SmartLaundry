import assert from 'node:assert/strict';
import { writeFileSync } from 'node:fs';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const base=process.env.ADMIN_URL || 'http://127.0.0.1:8081';
if (process.env.E2E_ALLOW_WRITES !== '1') throw new Error('Set E2E_ALLOW_WRITES=1 hanya untuk database uji terpisah.');
if (!['127.0.0.1','localhost'].includes(new URL(base).hostname)) throw new Error('Browser write test hanya untuk host lokal.');
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1440,height:900}});
const errors=[]; page.on('pageerror',e=>errors.push(e.message));
const money=async selector=>Number((await page.locator(selector).innerText()).replace(/\D/g,''));
const stamp=Date.now().toString().slice(-9);
try {
 await page.goto(base+'/operasional.html#customers');
 await page.locator('#customers-state').getByText('Belum ada pelanggan', {exact:false}).waitFor({state:'attached'});
 await page.locator('#orders-state').getByText('Belum ada order', {exact:false}).waitFor({state:'attached'});
 console.log('Empty states: customers and orders OK');
 await page.goto(base+'/operasional.html#services');
 await page.locator('#service-name').fill('Layanan E2E '+stamp);
 await page.locator('#service-category').fill('uji');
 await page.locator('#service-description').fill('Uji lengkap');
 await page.locator('#service-price-kg').fill('7000');
 await page.locator('#service-price-item').fill('21000');
 await page.locator('#service-duration').fill('120');
 await page.locator('#service-submit').click();
 await page.locator('#operasional-services').getByText('Layanan E2E '+stamp).waitFor();
 const serviceId=await page.locator('#operasional-service option').filter({hasText:'Layanan E2E '+stamp}).getAttribute('value');
 assert.ok(serviceId);
 await page.locator(`[data-edit-service="${serviceId}"]`).click();
 await page.locator('#service-price-item').fill('22000');
 await page.locator('#service-submit').click();
 await page.waitForFunction(id=>[...document.querySelectorAll('#operasional-services article')].some(card=>card.textContent.includes('Layanan E2E')&&card.textContent.includes('22.000')),serviceId);
 console.log('Catalog create/update OK:',serviceId);
 await page.goto(base+'/operasional.html#customers');
 const customerName='Pelanggan E2E '+stamp;
 await page.locator('#customer-name-pos').fill(customerName);
 await page.locator('#customer-whatsapp').fill('0812'+stamp);
 await page.locator('#customer-submit').click();
 await page.locator('#customer-rows').getByText(customerName).waitFor();
 await page.locator('#customer-search').fill(stamp);
 assert.equal(await page.locator('#customer-rows tr').count(),1);
 const customerId=await page.locator('#operasional-customer option').filter({hasText:customerName}).getAttribute('value');
 assert.ok(customerId);
 console.log('Customer create/search OK:',customerId);
 await page.goto(base+'/operasional.html#new-order');
 const key1=await page.locator('#client-order-id').inputValue();
 assert.ok(key1);
 await page.locator('#operasional-customer').selectOption(customerId);
 await page.locator('#operasional-service').selectOption('regular');
 await page.locator('#operasional-unit').selectOption('kg');
 await page.locator('#operasional-quantity').fill('2,5');
 await page.locator('#add-order-item').click();
 assert.equal(await page.locator('#order-items [data-order-item]').count(),2);
 const second=page.locator('#order-items [data-order-item]').nth(1);
 await second.locator('.order-service-select').selectOption(serviceId);
 await second.locator('.order-unit-select').selectOption('item');
 await second.locator('.order-quantity-input').fill('2');
 await page.locator('#operasional-discount').fill('1000');
 await page.locator('#operasional-note').fill('Pisahkan warna');
 await page.locator('#operasional-order-form button[type=submit]').click();
 await page.locator('#summary-content').waitFor({state:'visible'});
 assert.equal(await money('#summary-total'),58000);
 assert.ok((await page.locator('#summary-service').innerText()).includes('Layanan E2E'));
 assert.equal(await page.locator('#order-items [data-order-item]').count(),1);
 const key2=await page.locator('#client-order-id').inputValue();
 assert.ok(key2 && key2!==key1,'ID order tidak diperbarui setelah reset');
 let orders=(await (await fetch(base+'/api/orders')).json()).orders;
 assert.equal(orders.length,1);
 const firstId=orders[0].id;
 assert.equal(await page.locator('#summary-tracking-code').innerText(),firstId);
 const detail=(await (await fetch(base+'/api/orders/'+firstId)).json()).order;
 assert.equal(detail.items.length,2);
 assert.equal(detail.total,58000);
 console.log('Multi-item order and server total OK:',firstId);
 // Ulangi permintaan yang sama persis; API harus mengembalikan order lama.
 const replay=await fetch(base+'/api/orders',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({client_order_id:key1,customer_id:customerId,items:[{service_id:'regular',unit:'kg',quantity:2.5},{service_id:serviceId,unit:'item',quantity:2}],discount:1000,note:'Pisahkan warna'})});
 const replayBody=await replay.json();
 assert.equal(replay.status,200,JSON.stringify(replayBody));
 assert.equal(replayBody.order.id,firstId);
 assert.equal((await (await fetch(base+'/api/orders')).json()).orders.length,1);
 console.log('Idempotent request OK');
 // Order berikutnya membuktikan client_order_id baru tetap terisi setelah form.reset().
 await page.locator('#operasional-customer').selectOption(customerId);
 await page.locator('#operasional-service').selectOption('regular');
 await page.locator('#operasional-unit').selectOption('item');
 await page.locator('#operasional-quantity').fill('1');
 await page.locator('#operasional-order-form button[type=submit]').click();
 await page.waitForFunction(()=>document.querySelector('#summary-total').textContent.replace(/\D/g,'')==='18000');
 orders=(await (await fetch(base+'/api/orders')).json()).orders;
 assert.equal(orders.length,2);
 const secondId=orders.find(order=>order.id!==firstId).id;
 console.log('Second UI order after reset OK:',secondId);
 await page.goto(base+'/operasional.html#orders');
 await page.locator(`#order-rows [data-order="${firstId}"]`).click();
 await page.locator('#dialog-body').getByText('Pisahkan warna').waitFor();
 assert.ok((await page.locator('#dialog-body').innerText()).includes(firstId));
 assert.equal(await page.locator('#dialog-status option:checked').innerText(),'Antre');
 await page.locator('#payment-amount').fill('10000');
 await page.locator('#payment-form button[type=submit]').click();
 await page.locator('#dialog-body h3').filter({hasText:'DP'}).waitFor();
 await page.locator('#payment-amount').fill('48000');
 await page.locator('#payment-method').selectOption('qris');
 await page.locator('#payment-form button[type=submit]').click();
 await page.locator('#dialog-body h3').filter({hasText:'Lunas'}).waitFor();
 for(const [value,label] of [['diproses','Diproses'],['selesai','Siap diambil'],['diambil','Selesai']]) {
  await page.locator('#dialog-status').selectOption(value);
  await page.locator('#status-form button[type=submit]').click();
  await page.locator('#dialog-body').getByText(label,{exact:true}).waitFor();
 }
 const paid=(await (await fetch(base+'/api/orders/'+firstId)).json()).order;
 assert.equal(paid.paid_amount,58000);
 assert.equal(paid.payment_status,'lunas');
 assert.equal(paid.status,'diambil');
 console.log('DP/lunas and status Antre → Diproses → Siap diambil → Selesai OK');
 await page.locator('#dialog-receipt').click();
 await page.locator('#receipt-paper').getByText('STRUK ORDER TERSIMPAN').waitFor();
 assert.ok((await page.locator('#receipt-paper').innerText()).includes('Layanan E2E'));
 assert.ok((await page.locator('#receipt-paper').innerText()).includes('Lunas'));
 assert.ok((await page.locator('#receipt-paper').innerText()).includes(firstId));
 await page.evaluate(()=>{window.print=()=>{window.__printed=true;};});
 await page.locator('#print-receipt').click();
 assert.equal(await page.evaluate(()=>window.__printed),true);
 await page.emulateMedia({media:'print'});
 assert.equal(await page.locator('#receipt-paper').evaluate(el=>getComputedStyle(el).display),'block');
 assert.equal(await page.locator('.operasional-sidebar').evaluate(el=>getComputedStyle(el).display),'none');
 await page.emulateMedia({media:'screen'});
 console.log('Receipt data and browser print action/CSS OK');
 await page.goto(base+'/operasional.html#expenses');
 await page.locator('#expense-category').fill('Bahan');
 await page.locator('#expense-amount').fill('3000');
 await page.locator('#expense-description').fill('Deterjen E2E '+stamp);
 await page.locator('#expense-form button[type=submit]').click();
 await page.locator('#expense-rows').getByText('Deterjen E2E '+stamp).waitFor();
 await page.locator('#report-form button[type=submit]').click();
 await page.waitForFunction(()=>document.querySelector('#report-payments').textContent.replace(/\D/g,'')==='58000');
 assert.equal(await money('#report-expenses'),3000);
 assert.equal(await money('#report-balance'),55000);
 console.log('Expense/report OK');
 assert.deepEqual(errors,[]);
 writeFileSync(new URL('./.e2e-state.json', import.meta.url),JSON.stringify({firstId,secondId,serviceId,customerId}));
 console.log('Admin UI full flow: PASS');
} finally {await browser.close();}
